-- Tipo equivalente al MEDIUMTEXT de MySQL que usan algunas entidades.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'mediumtext') THEN
        CREATE DOMAIN mediumtext AS text;
    END IF;
END $$;

-- 1. USUARIOS
CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'OPERADOR'
        CHECK (rol IN ('ADMIN', 'OPERADOR', 'CALIDAD', 'SUPERVISOR')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. PRODUCTOS
CREATE TABLE IF NOT EXISTS producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    categoria VARCHAR(100),
    descripcion TEXT,
    temperatura_min NUMERIC(5,2),
    temperatura_max NUMERIC(5,2),
    humedad_min NUMERIC(5,2),
    humedad_max NUMERIC(5,2),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_producto_temperatura CHECK (temperatura_min IS NULL OR temperatura_max IS NULL OR temperatura_min <= temperatura_max),
    CONSTRAINT chk_producto_humedad CHECK (humedad_min IS NULL OR humedad_max IS NULL OR humedad_min <= humedad_max),
    CONSTRAINT chk_producto_humedad_rango CHECK (humedad_min IS NULL OR (humedad_min >= 0 AND humedad_min <= 100)),
    CONSTRAINT chk_producto_humedad_max_rango CHECK (humedad_max IS NULL OR (humedad_max >= 0 AND humedad_max <= 100))
);

-- 3. LOTES
CREATE TABLE IF NOT EXISTS lote (
    id_lote BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
    codigo_lote VARCHAR(80) NOT NULL UNIQUE,
    fecha_produccion DATE,
    fecha_vencimiento DATE,
    cantidad NUMERIC(12,3) NOT NULL DEFAULT 0,
    unidad VARCHAR(30) NOT NULL DEFAULT 'UNIDAD',
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado IN ('DISPONIBLE', 'BLOQUEADO', 'EN_TRANSITO', 'ENTREGADO', 'DESCARTADO')),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_lote_cantidad CHECK (cantidad >= 0),
    CONSTRAINT chk_lote_fechas CHECK (fecha_produccion IS NULL OR fecha_vencimiento IS NULL OR fecha_produccion <= fecha_vencimiento)
);
CREATE INDEX IF NOT EXISTS idx_lote_producto ON lote (id_producto);
CREATE INDEX IF NOT EXISTS idx_lote_estado ON lote (estado);
CREATE INDEX IF NOT EXISTS idx_lote_vencimiento ON lote (fecha_vencimiento);

-- 4. DESPACHOS
CREATE TABLE IF NOT EXISTS despacho (
    id_despacho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE,
    transportista VARCHAR(150),
    vehiculo VARCHAR(100),
    placa VARCHAR(20),
    destino VARCHAR(150) NOT NULL,
    direccion_destino VARCHAR(255),
    contacto_destino VARCHAR(150),
    fecha_programada TIMESTAMP,
    fecha_salida TIMESTAMP,
    fecha_llegada TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'PREPARACION', 'EN_TRANSITO', 'ENTREGADO', 'CANCELADO')),
    observacion TEXT,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_despacho_estado ON despacho (estado);
CREATE INDEX IF NOT EXISTS idx_despacho_fecha_programada ON despacho (fecha_programada);

-- 5. LOTES POR DESPACHO
CREATE TABLE IF NOT EXISTS despacho_lote (
    id_despacho_lote BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_despacho BIGINT NOT NULL REFERENCES despacho(id_despacho) ON DELETE CASCADE,
    id_lote BIGINT NOT NULL REFERENCES lote(id_lote),
    cantidad NUMERIC(12,3) NOT NULL,
    CONSTRAINT uq_despacho_lote UNIQUE (id_despacho, id_lote),
    CONSTRAINT chk_despacho_lote_cantidad CHECK (cantidad > 0)
);
CREATE INDEX IF NOT EXISTS idx_despacho_lote_despacho ON despacho_lote (id_despacho);
CREATE INDEX IF NOT EXISTS idx_despacho_lote_lote ON despacho_lote (id_lote);

-- 6. CONTROLES
CREATE TABLE IF NOT EXISTS control (
    id_control BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_despacho BIGINT NOT NULL REFERENCES despacho(id_despacho),
    id_lote BIGINT NOT NULL REFERENCES lote(id_lote),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    temperatura NUMERIC(5,2),
    humedad NUMERIC(5,2),
    resultado VARCHAR(20) NOT NULL CHECK (resultado IN ('NORMAL', 'FUERA_RANGO')),
    observacion TEXT,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    CONSTRAINT chk_control_humedad CHECK (humedad IS NULL OR (humedad >= 0 AND humedad <= 100))
);
CREATE INDEX IF NOT EXISTS idx_control_despacho ON control (id_despacho);
CREATE INDEX IF NOT EXISTS idx_control_lote ON control (id_lote);
CREATE INDEX IF NOT EXISTS idx_control_fecha ON control (fecha_hora);
CREATE INDEX IF NOT EXISTS idx_control_resultado ON control (resultado);

-- 7. INCIDENCIAS
CREATE TABLE IF NOT EXISTS incidencia (
    id_incidencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_control BIGINT REFERENCES control(id_control),
    id_lote BIGINT NOT NULL REFERENCES lote(id_lote),
    id_despacho BIGINT REFERENCES despacho(id_despacho),
    tipo VARCHAR(20) NOT NULL DEFAULT 'OTRA'
        CHECK (tipo IN ('TEMPERATURA', 'HUMEDAD', 'CALIDAD', 'LOGISTICA', 'OTRA')),
    descripcion TEXT NOT NULL,
    prioridad VARCHAR(20) NOT NULL DEFAULT 'MEDIA'
        CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    estado VARCHAR(20) NOT NULL DEFAULT 'ABIERTA'
        CHECK (estado IN ('ABIERTA', 'EN_PROCESO', 'RESUELTA', 'CERRADA')),
    causa TEXT,
    accion TEXT,
    responsable BIGINT REFERENCES usuario(id_usuario),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_incidencia_estado ON incidencia (estado);
CREATE INDEX IF NOT EXISTS idx_incidencia_prioridad ON incidencia (prioridad);
CREATE INDEX IF NOT EXISTS idx_incidencia_lote ON incidencia (id_lote);
CREATE INDEX IF NOT EXISTS idx_incidencia_despacho ON incidencia (id_despacho);

-- 8. EVIDENCIAS
CREATE TABLE IF NOT EXISTS evidencia (
    id_evidencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia BIGINT NOT NULL REFERENCES incidencia(id_incidencia) ON DELETE CASCADE,
    tipo VARCHAR(50) NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    url VARCHAR(500),
    descripcion VARCHAR(500),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario)
);
CREATE INDEX IF NOT EXISTS idx_evidencia_incidencia ON evidencia (id_incidencia);

-- 9. EVENTOS / TRAZABILIDAD
CREATE TABLE IF NOT EXISTS evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote BIGINT REFERENCES lote(id_lote),
    id_despacho BIGINT REFERENCES despacho(id_despacho),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('CREACION_LOTE', 'PREPARACION', 'CONTROL', 'SALIDA', 'CAMBIO_UBICACION',
        'LLEGADA', 'BLOQUEO_LOTE', 'LIBERACION_LOTE', 'DESCARTE_LOTE', 'ENTREGA', 'OTRO')),
    descripcion TEXT,
    ubicacion VARCHAR(255),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario)
);
CREATE INDEX IF NOT EXISTS idx_evento_lote_fecha ON evento (id_lote, fecha_hora);
CREATE INDEX IF NOT EXISTS idx_evento_despacho_fecha ON evento (id_despacho, fecha_hora);
CREATE INDEX IF NOT EXISTS idx_evento_tipo ON evento (tipo);

-- 10. COMPROBANTES ELECTRÓNICOS
CREATE TABLE IF NOT EXISTS comprobante (
    id_comprobante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(2) NOT NULL,
    serie VARCHAR(4) NOT NULL,
    correlativo BIGINT NOT NULL,
    fecha_emision TIMESTAMP NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'PEN',
    cliente_tipo_doc VARCHAR(1) NOT NULL,
    cliente_num_doc VARCHAR(15) NOT NULL,
    cliente_nombre VARCHAR(200) NOT NULL,
    cliente_direccion VARCHAR(255),
    op_gravada NUMERIC(12,2) NOT NULL DEFAULT 0,
    igv NUMERIC(12,2) NOT NULL DEFAULT 0,
    total NUMERIC(12,2) NOT NULL DEFAULT 0,
    id_despacho BIGINT REFERENCES despacho(id_despacho),
    datos_traslado TEXT,
    observacion VARCHAR(500),
    entorno VARCHAR(12) NOT NULL DEFAULT 'BETA',
    estado_sunat VARCHAR(20) NOT NULL
        CHECK (estado_sunat IN ('PENDIENTE', 'ACEPTADO', 'OBSERVADO', 'RECHAZADO', 'ERROR', 'NO_ENVIADO')),
    codigo_respuesta VARCHAR(10),
    descripcion_respuesta TEXT,
    observaciones_sunat TEXT,
    hash VARCHAR(100),
    xml_firmado mediumtext,
    cdr_base64 mediumtext,
    fecha_envio TIMESTAMP,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_comprobante_numero UNIQUE (tipo, serie, correlativo)
);
CREATE INDEX IF NOT EXISTS idx_comprobante_tipo_fecha ON comprobante (tipo, fecha_emision);
CREATE INDEX IF NOT EXISTS idx_comprobante_cliente ON comprobante (cliente_num_doc);

CREATE TABLE IF NOT EXISTS comprobante_item (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comprobante BIGINT NOT NULL REFERENCES comprobante(id_comprobante) ON DELETE CASCADE,
    orden INT NOT NULL,
    codigo VARCHAR(50),
    descripcion VARCHAR(500) NOT NULL,
    unidad VARCHAR(5) NOT NULL,
    cantidad NUMERIC(12,3) NOT NULL,
    valor_unitario NUMERIC(16,6) NOT NULL DEFAULT 0,
    precio_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    valor_venta NUMERIC(12,2) NOT NULL DEFAULT 0,
    igv NUMERIC(12,2) NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_item_comprobante ON comprobante_item (id_comprobante);

-- Inmutabilidad (RB-07): evento y control solo admiten inserciones.
CREATE OR REPLACE FUNCTION fn_registro_inmutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0];
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_evento_no_update ON evento;
CREATE TRIGGER trg_evento_no_update BEFORE UPDATE ON evento
    FOR EACH ROW EXECUTE FUNCTION fn_registro_inmutable('Los eventos son inmutables: no se pueden modificar.');
DROP TRIGGER IF EXISTS trg_evento_no_delete ON evento;
CREATE TRIGGER trg_evento_no_delete BEFORE DELETE ON evento
    FOR EACH ROW EXECUTE FUNCTION fn_registro_inmutable('Los eventos son inmutables: no se pueden eliminar.');
DROP TRIGGER IF EXISTS trg_control_no_update ON control;
CREATE TRIGGER trg_control_no_update BEFORE UPDATE ON control
    FOR EACH ROW EXECUTE FUNCTION fn_registro_inmutable('Los controles son inmutables: no se pueden modificar.');
DROP TRIGGER IF EXISTS trg_control_no_delete ON control;
CREATE TRIGGER trg_control_no_delete BEFORE DELETE ON control
    FOR EACH ROW EXECUTE FUNCTION fn_registro_inmutable('Los controles son inmutables: no se pueden eliminar.');
